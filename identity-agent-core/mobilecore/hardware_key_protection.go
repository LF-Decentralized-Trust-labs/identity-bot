package mobilecore

import "identity-agent-core/secureenclave"

// Reporting what protects a key on this phone.
//
// On every other platform the core asks the operating system itself: macOS goes
// to the Security framework, Windows to the platform crypto provider, Linux to
// the device nodes. Android's Keystore is a Java API with no path to it from
// Go, so the app probes it and reports the result here. The core still owns
// what the answer MEANS — which statuses exist, and that only a proven one may
// hold a root key — and the app supplies only what it observed.
//
// [status] is one of "usable", "present_unusable", "absent" or "unknown", and
// they carry the meanings capability.go defines. In particular:
//
//   - "usable" is PROVEN, never inferred. A key must actually have been
//     generated in the Keystore and thrown away. Reading a feature flag, an API
//     level, or a device model is the guess this whole mechanism exists to stop.
//   - "absent" needs positive evidence that there is no hardware-backed
//     Keystore. An exception nobody recognised is "unknown", not "absent" —
//     telling somebody their phone has no security hardware when the truth is
//     that a call failed is a false statement about their property.
//
// [kind] should be "android_strongbox" when the key went to StrongBox and
// "android_tee" when it went to the trusted execution environment. The
// distinction is worth carrying: they are different hardware with different
// guarantees, and a phone that has only the TEE is still a phone that can hold
// a root key.
//
// [reason] is a short stable slug for support and for anything that has to
// explain a refusal. [detail] carries the raw platform exception, including its
// message — the first release's job is to find out what real phones actually
// say, and a message that was discarded is one nothing can learn from.
//
// Must be called before StartServer, like DeclareEntityType. An app that stays
// quiet gets "unknown", which is the honest answer for nobody having looked and
// is never rendered as a claim about the phone.
func DeclareHardwareKeyProtection(status, kind, reason, detail string) {
	secureenclave.DeclareHardwareKeyProtection(status, kind, reason, detail)
}

// SeedWrapHost is the app's half of protecting the root seed on a phone: it
// holds the key in the Keystore, because Go cannot reach the Keystore, and
// proves where the key lives.
//
// On Android implement it with a non-exportable 2048-bit RSA key (decrypt
// purpose, OAEP with SHA-256 and the Keystore's SHA-1 mask, no user-authentication
// requirement because the agent runs with nobody present), generated by the
// Keystore in StrongBox first (setIsStrongBoxBacked(true)) and in the TEE if
// the phone has no StrongBox, with the attestation challenge
// [SeedWrapAttestationChallenge]. RSA and not AES because Android attests only
// asymmetric keys.
//
// [AttestationChain] is that key's certificate chain, leaf first, each
// certificate's DER preceded by its length as 4 bytes big-endian. The core
// checks it back to Google's attestation root and reads StrongBox or TEE out of
// it: the app does not say which hardware holds the key, and cannot. The core
// also does the wrapping itself, to the attested public key; [UnwrapKey] only
// decrypts a data key inside the hardware.
//
// The core uses it only while the key protection declared through
// DeclareHardwareKeyProtection is "usable" and the attestation checks out, so a
// phone with no proven hardware Keystore is refused instead of being given a
// wrapper that is not hardware.
type SeedWrapHost interface {
	Available() bool
	AttestationChain() []byte
	UnwrapKey(wrapped []byte) ([]byte, error)
}

// SeedWrapAttestationChallenge is the challenge the key must be generated with.
func SeedWrapAttestationChallenge() string { return secureenclave.SeedWrapAttestationChallenge }

// DeclareSeedWrapHost registers the app's seed wrapper. Must be called before
// StartServer, like DeclareHardwareKeyProtection. An app that registers none is
// refused in a production build: nothing that founds, restores or stores a seed
// writes one, and the refusal says why. Only a development build may store the
// seed unwrapped, and it says so.
func DeclareSeedWrapHost(h SeedWrapHost) {
	if h == nil {
		secureenclave.DeclareSeedWrapHost(nil)
		return
	}
	secureenclave.DeclareSeedWrapHost(h)
}

// DeclareAppIdentity says, at runtime, which app this is. It counts only in a
// development build whose core has no app identity built in, and the seed file
// and the log then say so. A production build ignores it: the package name and
// signing-certificate digests the seed key's attestation is held to are built
// into the core with linker flags, because an app that reads them from the
// system at runtime gets whatever app is running, a repackaged copy included:
//
//	gomobile bind -ldflags "-X identity-agent-core/secureenclave.builtAppPackage=<package name> -X identity-agent-core/secureenclave.builtAppSignerDigests=<sha256 hex>[,<sha256 hex>...]" ...
//
// A production core built without them refuses the attestation and says how to
// set them. [signerDigests] are the SHA-256 digests of the app's signing
// certificates in hex, separated by commas (more than one lets a signing key be
// rotated). Must be called before StartServer.
func DeclareAppIdentity(packageName, signerDigests string) error {
	digests, err := secureenclave.ParseSignerDigests(signerDigests)
	if err != nil {
		return err
	}
	return secureenclave.DeclareAppIdentity(packageName, digests)
}
